def test_wrap_and_differences():
    assert hc.wrap180(359.9) == pytest.approx(-0.1)
    assert hc.wrap180(-359.9) == pytest.approx(0.1)
    # azimuth across north: Horizons 0.1, ours 359.9 -> +0.2 deg, scaled by cos(el)
    d_el, d_az = hc.differences(359.9, 60.0, 0.1, 60.01)
    assert d_el == pytest.approx(0.01)
    assert d_az == pytest.approx(0.2 * 0.5)


def test_summarize_groups():
    pairs = [
        {"body": "sun", "on_sample": True, "d_el_deg": -0.001, "d_az_cos_el_deg": 0.002},
        {"body": "earth", "on_sample": False, "d_el_deg": 0.003, "d_az_cos_el_deg": -0.004},
        {"body": "earth", "on_sample": True, "d_el_deg": 0.0, "d_az_cos_el_deg": 0.0},
    ]
