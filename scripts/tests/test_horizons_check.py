def test_reproduces_v1_row_1_from_shipped_ephemeris():
    """V1 row 1 (docs/event/validation.md): Connecting Ridge, 14 Nov 2026 00:00, Sun 263.2832 / 1.4935, 1.75 m on the sphere."""
    path = hc.DATA / "ephem" / "2026-11.json"
    if not path.exists():
        pytest.skip("shipped ephemeris not present")
    month = json.loads(path.read_text(encoding="utf-8"))
    v, on = hc.interpolate(month, dt.datetime(2026, 11, 14, tzinfo=UTC), "sun")
    assert on
    az, el = hc.az_el(v, hc.site_vector(-89.46, -136.68, 0.00175), hc.enu_basis(-89.46, -136.68))
    assert az == pytest.approx(263.2832, abs=1e-4)
    assert el == pytest.approx(1.4935, abs=1e-4)
