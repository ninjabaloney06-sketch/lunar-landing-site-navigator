"""Cross-language fixtures (build-plan §3, §4.5; T9): app/src/test/fixtures.json.

200 random (site, time) cases in 2026-11 .. 2027-12. For each, the Python reference (scripts/windows.py) reads
the shipped ephem month files, interpolates exactly like app/src/geometry (vectors linear, quaternions slerp),
and records the body state, Sun/Earth az/el, mask, visible fraction and visibility, and each station's line of
sight. app/src/geometry/fixtures.test.ts must reproduce every angle to 1e-6 deg.

Interpolation accuracy against direct SPICE (< 0.001 deg) is tested separately in
scripts/tests/test_ephemeris.py; these fixtures pin the browser to the Python reference.

    python3 scripts/export_fixtures.py
"""
import json
import random
import sys
from datetime import datetime, timezone

import windows as geo
from config import APP_DATA, REPO

OUT = REPO / "app" / "src" / "test" / "fixtures.json"
N_CASES = 200
SEED = 20261114
T0 = datetime(2026, 11, 1, tzinfo=timezone.utc)
T1 = datetime(2028, 1, 1, tzinfo=timezone.utc)
SAMPLE_HORIZON = "sample-site.json"

# Fixture sites. The three in app/public/data/sites.json, Connecting Ridge (agent-briefs, Brief A done-check),
# and one synthetic elevated point that exercises the elev_m path (test input only, not a real site).
EXTRA_SITES = [
    {"id": "connecting-ridge", "lat": -89.46, "lon": -136.68, "elev_m": None},
    {"id": "synthetic-elevated", "lat": -88.0, "lon": 45.0, "elev_m": 2000.0},
]


def months_needed():
    y, m = T0.year, T0.month
    while (y, m) < (T1.year, T1.month):
        yield f"{y}-{m:02d}"
        y, m = (y + 1, 1) if m == 12 else (y, m + 1)


def main():
    sites = [{"id": s["id"], "lat": s["lat"], "lon": s["lon"], "elev_m": s.get("elev_m")}
             for s in json.loads((APP_DATA / "sites.json").read_text())]
    sites += [s for s in EXTRA_SITES if s["id"] not in {x["id"] for x in sites}]
    horizon = json.loads((APP_DATA / "horizons" / SAMPLE_HORIZON).read_text())
    stations_raw = json.loads((APP_DATA / "stations.json").read_text())
    stations = [{k: v for k, v in s.items() if not k.startswith("_")} for s in stations_raw]
    synthetic = any("SYNTHETIC" in (s.get("_note", "") + s.get("source_label", "")) for s in stations_raw)
    month_ids = list(months_needed())
    months = [geo.load_month(APP_DATA / "ephem" / f"{m}.json") for m in month_ids]

    rng = random.Random(SEED)
    t0_ms = int(T0.timestamp() * 1000)
    t1_ms = int(T1.timestamp() * 1000)
    cases = []
    for i in range(N_CASES):
        site = sites[i % len(sites)]
        hz_name = SAMPLE_HORIZON if rng.random() < 0.5 else None
        utc_ms = rng.randrange(t0_ms, t1_ms - 60_000, 1000)  # whole seconds, arbitrary step fraction
        state = geo.interpolate(months, utc_ms)
        smp = geo.sample(state, site, horizon if hz_name else None, stations)
        cases.append({
            "site": site["id"],
            "horizon": hz_name,
            "utc": geo.ms_to_iso(utc_ms),
            "utcMs": utc_ms,
            "state": {k: state[k] for k in ("sun_km", "earth_km", "q_me_to_j2000", "q_earth_to_me")},
            "sun": smp["sun"],
            "earth": smp["earth"],
            "stations": smp["stations"],
            "coverage_all": geo.coverage_state(smp, [s["id"] for s in stations]),
        })

    out = {
        "_note": "Generated by scripts/export_fixtures.py (T9). Python reference over the shipped ephem files; "
                 "the TypeScript geometry must match every angle to 1e-6 deg."
                 + (" Station rows are the SYNTHETIC sample stations.json (test input only)." if synthetic else ""),
        "tolerance_deg": 1e-6,
        "observer_height_m": geo.OBSERVER_HEIGHT_M,
        "ephem_months": month_ids,
        "horizon_files": [SAMPLE_HORIZON],
        "sites": {s["id"]: {"lat": s["lat"], "lon": s["lon"], "elev_m": s["elev_m"]} for s in sites},
        "stations": stations,
        "cases": cases,
    }
    OUT.write_text(json.dumps(out, separators=(",", ":")) + "\n")
    lit = sum(c["sun"]["lit"] for c in cases)
    vis = sum(c["earth"]["visible"] for c in cases)
    partial = sum(0 < c["sun"]["frac"] < 1 for c in cases)
    los = sum(r["state"] == "los" for c in cases for r in c["stations"].values())
    print(f"wrote {OUT.relative_to(REPO)}: {len(cases)} cases, {len(sites)} sites, {len(stations)} stations "
          f"({'synthetic' if synthetic else 'sourced'}); Sun lit {lit}, partial disc {partial}, Earth visible {vis}, "
          f"station LOS {los}; {OUT.stat().st_size / 1024:.0f} KB")


if __name__ == "__main__":
    sys.exit(main())
