"""Sun and Earth azimuth/elevation from the app's shipped ephemeris, compared with JPL Horizons.

Generated by an AI tool (Claude Code) on 15 Nov 2026. Not a sign-off by the science lead.

Ours: the files the browser loads (app/public/data/ephem/YYYY-MM.json: Moon centre -> Sun / Earth in MOON_ME, km,
LT+S, every 30 min) and the app's own maths re-written in Python (app/src/geometry/index.ts): `interpolate`
(vectors linear between samples), `siteVector` ((1737.4 km + elev_m + 1.75 m) * unit(lat, lon)), `enuBasis`
(up = unit(lat, lon), east = unit(z x up), north = up x east) and `azEl` (body - site, rotated into ENU;
az 0 = north, clockwise).

Theirs: the public Horizons API, observer table, observer on the Moon at the same point
(CENTER='coord@301', COORD_TYPE='GEODETIC', SITE_COORD='lonE,lat,alt_km'), targets 10 and 399, QUANTITIES='4'
(apparent az/el), APPARENT='AIRLESS'. One request per site and body with a TLIST of instants, sent one after another.

Run from the repo root:  python3 scripts/tools/horizons_check.py
Writes app/public/data/validation/horizons.json and prints the summary. Needs network; standard library only.
"""

from __future__ import annotations

import datetime as dt
import json
import math
import statistics
import sys
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "app" / "public" / "data"
OUT = DATA / "validation" / "horizons.json"
API = "https://ssd.jpl.nasa.gov/api/horizons.api"

MOON_RADIUS_KM = 1737.4  # app/src/geometry/index.ts MOON_RADIUS_KM
OBSERVER_HEIGHT_M = 1.75  # app/src/geometry/index.ts OBSERVER_HEIGHT_M
TOLERANCE_DEG = 0.05  # V1 tolerance, docs/event/validation.md
BODIES = {"sun": "10", "earth": "399"}
SITE_IDS = ["connecting-ridge", "shackleton-rim-site04", "im-1"]
# Minutes past the hour for instants between the 30-min samples (15 and 45 = mid-step, the worst case for lerp).
BETWEEN_MINUTES = [15, 7, 44, 22, 51, 38]


# ---------- the app's maths ----------

def site_vector(lat: float, lon: float, h_km: float) -> tuple[float, float, float]:
    r = MOON_RADIUS_KM + h_km
    la, lo = math.radians(lat), math.radians(lon)
    return (r * math.cos(la) * math.cos(lo), r * math.cos(la) * math.sin(lo), r * math.sin(la))


def _cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def _dot(a, b):
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def _unit(a):
    n = math.sqrt(_dot(a, a))
    return (a[0] / n, a[1] / n, a[2] / n)


def enu_basis(lat: float, lon: float):
    up = _unit(site_vector(lat, lon, 0.0))
    east = _unit(_cross((0.0, 0.0, 1.0), up))
    north = _cross(up, east)
    return east, north, up


def az_el(body_km, site_km, enu) -> tuple[float, float]:
    east, north, up = enu
    u = _unit((body_km[0] - site_km[0], body_km[1] - site_km[1], body_km[2] - site_km[2]))
    e, n, z = _dot(u, east), _dot(u, north), _dot(u, up)
    az = math.degrees(math.atan2(e, n))
    if az < 0:
        az += 360.0
    return az, math.degrees(math.atan2(z, math.hypot(e, n)))


def site_height_km(elev_m: float | None) -> float:
    return ((elev_m or 0.0) + OBSERVER_HEIGHT_M) / 1000.0


def interpolate(month: dict, t: dt.datetime, body: str) -> tuple[tuple[float, float, float], bool]:
    """Body vector at t (linear between samples, as the app). Returns (vector, t is a sample time)."""
    t0 = dt.datetime.fromisoformat(month["start_utc"].replace("Z", "+00:00"))
    x = (t - t0).total_seconds() / 60.0 / month["step_min"]
    i = math.floor(x)
    if not 0 <= i < month["n"] - 1:
        raise ValueError(f"{t.isoformat()} is not inside {month['start_utc']} + {month['n']} samples")
    f = x - i
    a, b = month[f"{body}_km"][i], month[f"{body}_km"][i + 1]
    return tuple(a[k] + (b[k] - a[k]) * f for k in range(3)), f == 0.0


# ---------- instants ----------

def instants(site_index: int, count: int = 12) -> list[tuple[dt.datetime, bool]]:
    """Deterministic instants across 2027-2030; even k on a 30-min sample, odd k between samples."""
    out = []
    for k in range(count):
        year = 2027 + (k * 4) // count
        month = 1 + (3 * k + 4 * site_index) % 12
        day = 3 + 7 * ((k + site_index) % 4)
        hour = (5 * k + 7 * site_index) % 24
        if k % 2 == 0:
            minute, on = (0 if (k // 2) % 2 == 0 else 30), True
        else:
            minute, on = BETWEEN_MINUTES[(k // 2 + site_index) % len(BETWEEN_MINUTES)], False
        out.append((dt.datetime(year, month, day, hour, minute, tzinfo=dt.timezone.utc), on))
    return sorted(out)  # Horizons returns a TLIST in time order


# ---------- Horizons ----------

def horizons_params(lon: float, lat: float, alt_km: float, command: str, times: list[dt.datetime]) -> dict:
    tlist = " ".join(f"'{t:%Y-%m-%d %H:%M}'" for t in times)
    return {
        "format": "json",
        "COMMAND": f"'{command}'",
        "OBJ_DATA": "'NO'",
        "MAKE_EPHEM": "'YES'",
        "EPHEM_TYPE": "'OBSERVER'",
        "CENTER": "'coord@301'",
        "COORD_TYPE": "'GEODETIC'",
        "SITE_COORD": f"'{lon % 360:.6f},{lat:.6f},{alt_km:.6f}'",
        "TLIST": tlist,
        "TLIST_TYPE": "'CAL'",
        "TIME_TYPE": "'UT'",
        "QUANTITIES": "'4'",
        "ANG_FORMAT": "'DEG'",
        "EXTRA_PREC": "'YES'",
        "TIME_DIGITS": "'MINUTES'",
        "APPARENT": "'AIRLESS'",
        "CSV_FORMAT": "'YES'",
    }


_MONTHS = {m: i + 1 for i, m in enumerate(["Jan", "Feb", "Mar", "Apr", "May", "Jun",
                                           "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"])}


def parse_horizons(text: str) -> list[tuple[dt.datetime, float, float]]:
    """Rows between $$SOE and $$EOE of a CSV observer table with quantity 4: (UTC, az, el)."""
    if "$$SOE" not in text:
        raise ValueError("no $$SOE in Horizons result: " + text[-800:])
    body = text.split("$$SOE", 1)[1].split("$$EOE", 1)[0]
    rows = []
    for line in body.strip().splitlines():
        fields = [f.strip() for f in line.split(",")]
        date = fields[0]  # e.g. "2027-Aug-16 00:00" (A.D. prefix possible)
        date = date.replace("A.D.", "").strip()
        ymd, hm = date.split()
        y, mon, d = ymd.split("-")
        h, mi = hm.split(":")[:2]
        t = dt.datetime(int(y), _MONTHS[mon], int(d), int(h), int(mi), tzinfo=dt.timezone.utc)
        nums = []
        for f in fields[1:]:
            try:
                nums.append(float(f))
            except ValueError:
                continue
        if len(nums) < 2:
            raise ValueError(f"cannot read az/el from row: {line!r}")
        rows.append((t, nums[0], nums[1]))
    return rows


def header_lines(text: str) -> dict:
    keys = ["Target body name", "Center body name", "Center geodetic", "Center pole/equ", "Center radii",
            "Atmos refraction", "RA format", "Time format"]
    out = {}
    for line in text.split("$$SOE", 1)[0].splitlines():
        for k in keys:
            if line.startswith(k) and k not in out:
                out[k] = " ".join(line.split(":", 1)[1].split())
    return out


def fetch(params: dict) -> dict:
    url = API + "?" + urllib.parse.urlencode(params)
    req = urllib.request.Request(url, headers={"User-Agent": "horizons-check-script/1.0"})
    with urllib.request.urlopen(req, timeout=90) as r:
        return json.loads(r.read().decode("utf-8"))


# ---------- comparison ----------

def wrap180(d: float) -> float:
    return (d + 180.0) % 360.0 - 180.0


def differences(ours_az: float, ours_el: float, h_az: float, h_el: float) -> tuple[float, float]:
    """(Δel, Δaz·cos el), Horizons − ours, degrees."""
    return h_el - ours_el, wrap180(h_az - ours_az) * math.cos(math.radians(ours_el))


def summarize(pairs: list[dict]) -> dict:
    def group(rows):
        if not rows:
            return {"pairs": 0}
        de = [abs(p["d_el_deg"]) for p in rows]
        da = [abs(p["d_az_cos_el_deg"]) for p in rows]
        return {
            "pairs": len(rows),
            "max_abs_d_el_deg": round(max(de), 9),
            "median_abs_d_el_deg": round(statistics.median(de), 9),
            "max_abs_d_az_cos_el_deg": round(max(da), 9),
            "median_abs_d_az_cos_el_deg": round(statistics.median(da), 9),
        }

    return {
        "all": group(pairs),
        "on_sample": group([p for p in pairs if p["on_sample"]]),
        "between_samples": group([p for p in pairs if not p["on_sample"]]),
        "sun": group([p for p in pairs if p["body"] == "sun"]),
        "earth": group([p for p in pairs if p["body"] == "earth"]),
    }


# ---------- run ----------

def main() -> int:
    sites = {s["id"]: s for s in json.loads((DATA / "sites.json").read_text(encoding="utf-8"))}
    month_cache: dict[str, dict] = {}

    def month_for(t: dt.datetime) -> dict:
        key = f"{t:%Y-%m}"
        if key not in month_cache:
            month_cache[key] = json.loads((DATA / "ephem" / f"{key}.json").read_text(encoding="utf-8"))
        return month_cache[key]

    pairs, queries, version, source = [], [], None, None
    for si, sid in enumerate(SITE_IDS):
        s = sites[sid]
        h_km = site_height_km(s.get("elev_m"))
        site_km = site_vector(s["lat"], s["lon"], h_km)
        enu = enu_basis(s["lat"], s["lon"])
        times = instants(si)
        for body, cmd in BODIES.items():
            res = fetch(horizons_params(s["lon"], s["lat"], h_km, cmd, [t for t, _ in times]))
            sig = res.get("signature", {})
            version, source = sig.get("version", version), sig.get("source", source)
            text = res["result"]
            hdr = header_lines(text)
            if "MEAN_ME" not in hdr.get("Center pole/equ", ""):
                raise SystemExit(f"{sid} {body}: Horizons frame is {hdr.get('Center pole/equ')!r}, not MEAN_ME")
            rows = parse_horizons(text)
            if [r[0] for r in rows] != [t for t, _ in times]:
                raise SystemExit(f"{sid} {body}: Horizons returned other times: {[r[0] for r in rows]}")
            queries.append({"site": sid, "body": body, "rows": len(rows), "header": hdr})
            for (t, on), (_, h_az, h_el) in zip(times, rows):
                vec, is_sample = interpolate(month_for(t), t, body)
                assert is_sample == on, (t, on)
                az, el = az_el(vec, site_km, enu)
                d_el, d_az = differences(az, el, h_az, h_el)
                pairs.append({
                    "site": sid, "utc": t.strftime("%Y-%m-%dT%H:%MZ"), "body": body, "on_sample": on,
                    "ours_az": round(az, 9), "ours_el": round(el, 9),
                    "horizons_az": h_az, "horizons_el": h_el,
                    "d_el_deg": round(d_el, 9), "d_az_cos_el_deg": round(d_az, 9),
                })

    summary = summarize(pairs)
    out = {
        "_note": ("Generated by an AI tool (Claude Code) on 15 Nov 2026 with scripts/tools/horizons_check.py. "
                  "Not a sign-off by the science lead. Δ = Horizons − ours, degrees."),
        "generated_by": "AI tool (Claude Code), 15 Nov 2026",
        "script": "scripts/tools/horizons_check.py",
        "date_run_utc": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "horizons_api": API,
        "horizons_api_version": version,
        "horizons_source": source,
        "horizons_settings": {k: v for k, v in horizons_params(0, 0, 0, "10", []).items()
                              if k not in ("COMMAND", "SITE_COORD", "TLIST", "format")},
        "ours": ("app/public/data/ephem/*.json (MOON_ME, LT+S, 30-min samples), vectors linear between samples; "
                 "observer at (1737.4 km + elev_m + 1.75 m) on the site's lat/lon (app/src/geometry/index.ts)"),
        "observer_height": "site elev_m from sites.json + 1.75 m above the 1737.4 km sphere, on both sides",
        "tolerance_deg": TOLERANCE_DEG,
        "summary": summary,
        "queries": queries,
        "pairs": pairs,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")

    print(f"Horizons API version {version}; {len(pairs)} pairs; written {OUT.relative_to(ROOT)}")
    for name, g in summary.items():
        if g["pairs"]:
            print(f"{name:16s} n={g['pairs']:3d}  |Δel| max {g['max_abs_d_el_deg']:.2e} median {g['median_abs_d_el_deg']:.2e}"
                  f"  |Δaz·cos el| max {g['max_abs_d_az_cos_el_deg']:.2e} median {g['median_abs_d_az_cos_el_deg']:.2e}")
    ok = summary["all"]["max_abs_d_el_deg"] < TOLERANCE_DEG and summary["all"]["max_abs_d_az_cos_el_deg"] < TOLERANCE_DEG
    print("within the V1 tolerance of 0.05°" if ok else "OUTSIDE the V1 tolerance of 0.05°")
    return 0


if __name__ == "__main__":
    sys.exit(main())
